Std_ReturnType Backend_BuildAppImage(uint32 swVersion, const uint8 *body, uint32 bodyLen,
                                     const uint8 flashKey[16], uint8 *out, uint32 outMax,
                                     uint32 *outLen)
{
    uint32 i;
    if ((body == NULL_PTR) || (out == NULL_PTR) || (outLen == NULL_PTR) || (bodyLen == 0u) ||
        (bodyLen > APP_BODY_MAX) || (outMax < (APP_HEADER_SIZE + bodyLen)))
    {
        return E_NOT_OK;
    }
    for (i = 0u; i < APP_HEADER_SIZE; i++)
    {
        out[i] = (i < APPHDR_OFF_MAC + APPHDR_MAC_LEN) ? 0x00u : 0xFFu;
    }
    AppHeader_Put32(&out[APPHDR_OFF_MAGIC], APPHDR_MAGIC);
    AppHeader_Put32(&out[APPHDR_OFF_HDRVER], APPHDR_VERSION);
    AppHeader_Put32(&out[APPHDR_OFF_SWVER], swVersion);
    AppHeader_Put32(&out[APPHDR_OFF_SIZE], bodyLen);
    AppHeader_Put32(&out[APPHDR_OFF_ENTRY], 0u);
    Hsm_Sha256(body, bodyLen, &out[APPHDR_OFF_DIGEST]);
    Hsm_Cmac(flashKey, out, APPHDR_SIGNED_LEN, &out[APPHDR_OFF_MAC]);
    for (i = 0u; i < bodyLen; i++)
    {
        out[APP_HEADER_SIZE + i] = body[i];
    }
    *outLen = APP_HEADER_SIZE + bodyLen;
    return E_OK;
}

void Backend_SecurityAccessKey(const uint8 diagKey[16], const uint8 *seed, uint32 seedLen, uint8 key[16])
{
    Hsm_Cmac(diagKey, seed, seedLen, key);
}

void Backend_BuildDemoAppBody(uint32 swVersion, uint8 *body, uint32 len)
{
    uint32 s = 0xA9900000u ^ swVersion;
    uint32 i;
    for (i = 0u; i < len; i++)
    {
        s = (s * 1664525u) + 1013904223u;
        body[i] = (uint8)(s >> 24);
    }
}
